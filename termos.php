  <h2 id="sec1"><span class="num">1.</span>O que é o Acervo de Treinos ClicTreino</h2>
  <p>O Acervo de Treinos ClicTreino é uma biblioteca digital de treinos pré-formatados e padronizados, organizados por objetivo, nível, tempo disponível e equipamento. O usuário utiliza filtros de busca para localizar treinos compatíveis com seu perfil e escolhe, entre as opções apresentadas, qual deseja acessar.</p>
  <p>O Acervo <strong>não constitui prescrição de exercício físico individualizada</strong> nem acompanhamento profissional personalizado. Trata-se de conteúdo de caráter geral e educativo, organizado em formato de catálogo, revisado periodicamente por profissional de Educação Física habilitado (CREF), que avalia o acervo como um todo — e não cada treino individualmente para cada usuário.</p>

  <h2 id="sec2"><span class="num">2.</span>Como funciona o acesso</h2>
  <p><strong>2.1.</strong> Ao utilizar os filtros de busca (objetivo, nível, tempo, equipamento), o usuário recebe de 2 (duas) a 3 (três) opções de treino do Acervo compatíveis com os critérios informados.</p>
  <p><strong>2.2.</strong> O usuário escolhe livremente, entre as opções apresentadas, qual treino deseja acessar. A escolha final é sempre do usuário.</p>
  <p><strong>2.3.</strong> O acesso ao treino escolhido é liberado de forma instantânea após a confirmação do pagamento (Pix), mediante o valor vigente informado no momento da compra (atualmente R$ 7,90 por acesso).</p>
  <p><strong>2.4.</strong> As informações fornecidas pelo usuário no filtro de busca servem exclusivamente para localizar conteúdo compatível dentro do Acervo já existente — não configuram coleta de dados de saúde para fins de prescrição individualizada.</p>

  <h2 id="sec3"><span class="num">3.</span>Quem pode usar</h2>
  <p><strong>3.1.</strong> O uso do Acervo de Treinos ClicTreino é destinado exclusivamente a pessoas maiores de 18 (dezoito) anos.</p>
  <p><strong>3.2.</strong> Não é permitido o uso por menores de 18 anos, ainda que com consentimento ou supervisão de responsável legal. Ao confirmar a compra, o usuário declara, sob as penas da lei, ser maior de idade.</p>

