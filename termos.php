  <p><strong>4.2.</strong> Recomenda-se fortemente que o usuário consulte médico e/ou profissional de Educação Física antes de iniciar qualquer programa de exercícios, especialmente em caso de condições de saúde preexistentes, lesões, gestação ou uso de medicamentos. Ver <a href="aviso-saude.php" style="color:#4fb6ff;">Aviso de Saúde</a> para detalhes completos.</p>
